def divisor(n):
    sum = []
    if n <= 1:
        sum.append(1)
        return sum
    else:
        for i in range(1, int(n**0.5) + 1):
            if n % i == 0:
                sum.append(i)
                if i != n // i:
                    sum.append(n // i)
        sum.sort()
        return sum

