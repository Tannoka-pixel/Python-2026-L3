import math

def is_prime(k):
    if k <= 1:
        return False
    for i in range(2, int(math.isqrt(k)) + 1):
        if k % i == 0:
            return False
    return True

def is_perfect(num):
    if num <= 0 or num % 2 != 0:
        return False  # All known perfect numbers are even positive integers

    n = 1
    while True:
        mersenne_candidate = (1 << (n + 1)) - 1  # Equivalent to 2^(n+1) - 1
        formula_val = (1 << n) * mersenne_candidate  # Equivalent to 2^n * (2^(n+1) - 1)

        if formula_val == num:
            # Check Euclid-Euler condition: n+1 and (2^(n+1) - 1) must both be prime
            return is_prime(n + 1) and is_prime(mersenne_candidate)

        if formula_val > num:
            return False

        n += 1

